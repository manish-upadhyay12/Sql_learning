/*
                   🟢 Question 1 — Product Quality Report
📖 Business Problem

The Quality Assurance Team wants to monitor customer ratings for each product.

👉 One row should represent one Product.

Display :  Product_Name
			Total_Reviews
			Average_Rating
			Highest_Rating
			Lowest_Rating
Conditions :
Rating IS NOT NULL
Delivery_Status = 'Delivered'

Sort By
Average_Rating DESC
✅ Solution
*/
SELECT
    product_name,
    COUNT(rating) AS total_reviews,
    ROUND(AVG(rating), 2) AS average_rating,
    MAX(rating) AS highest_rating,
    MIN(rating) AS lowest_rating
FROM shop_data
WHERE rating IS NOT NULL
  AND delivery_status = 'Delivered'
GROUP BY product_name
ORDER BY average_rating DESC;

            /*🟢 Question 2 — City Performance Report
📖 Business Problem

The Business Intelligence Team wants to compare sales performance across different cities.

👉 One row should represent one City.

Display :   City
			Total_Orders
			Total_Revenue
			Average_Order_Value
Conditions
Product_Category IN ('Electronics', 'Fashion', 'Furniture')
Delivery_Status = 'Delivered'
Total_Price > 2000

Sort By
Total_Revenue DESC
✅ Solution
*/
SELECT
    city,
    COUNT(*) AS total_orders,
    SUM(total_price) AS total_revenue,
    ROUND(AVG(total_price), 2) AS average_order_value
