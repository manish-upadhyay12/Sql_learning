 /*                     🟢 Question 4 — Executive Sales Audit (Boss Challenge)
📖 Business Problem
You are working as a Data Analyst at Amazon.
The CEO wants a report showing the sales performance of every Product Category.
👉 One row should represent one Product_Category.

Display : Product_Category
		Total_Orders
		Total_Revenue
		Average_Order_Value
		Highest_Order
		Lowest_Order
		Revenue_Level
		Revenue_Level Rules (CASE)
		Total_Revenue ≥ 100000 → Excellent
		Total_Revenue between 50000 and 99999.99 → Good
		Total_Revenue between 20000 and 49999.99 → Average
		Otherwise → Low
		
Conditions
		Delivery_Status = 'Delivered'
		Email ends with @gmail.com
		Rating >= 4
		Phone number has exactly 10 digits
		Transaction month is July, August, September, October, November, or December
		Product_Category IN ('Electronics', 'Fashion', 'Furniture')
		Total_Price IS NOT NULL

Sort By
Total_Revenue DESC
Average_Order_Value DESC
Product_Category ASC
✅ Solution
*/
SELECT
    product_category,
    COUNT(*) AS total_orders,
    SUM(total_price) AS total_revenue,
    ROUND(AVG(total_price), 2) AS average_order_value,
    MAX(total_price) AS highest_order,
    MIN(total_price) AS lowest_order,
    CASE
        WHEN SUM(total_price) >= 100000 THEN 'Excellent'
        WHEN SUM(total_price) BETWEEN 50000 AND 99999.99 THEN 'Good'
        WHEN SUM(total_price) BETWEEN 20000 AND 49999.99 THEN 'Average'
        ELSE 'Low'
    END AS revenue_level
FROM shop_data
WHERE delivery_status = 'Delivered'
  AND email LIKE '%@gmail.com'
  AND rating >= 4
  AND LENGTH(phone_number) = 10
  AND EXTRACT(MONTH FROM transaction_date) BETWEEN 7 AND 12
  AND product_category IN ('Electronics', 'Fashion', 'Furniture')
  AND total_price IS NOT NULL
GROUP BY product_category
ORDER BY total_revenue DESC,
         average_order_value DESC,
         product_category ASC;
		 