/*🟢 SQL Practice Set (10 Real Company Problems)
Question 1 – Customer Birthday Offer 🎂

The marketing team wants to send birthday offers to customers who made purchases in January.

Display:

Customer_Name
Email
Transaction_Date

Only include customers whose transaction month is January.

Sort the results by Transaction_Date (oldest first).
*/
SELECT customer_name,
	   email,
	   transaction_date
FROM shop_data
WHERE transaction_date BETWEEN '2024-01-01' AND '2024-01-31'
ORDER BY transaction_date asc;

/*
Question 2 – High Value Female Customers 💳

The sales manager wants a list of female customers who:

spent more than 3000
successfully received their orders

Display:

Customer_Name
Product_Name
Total_Price
Delivery_Status

Sort by Total_Price from highest to lowest.
*/
SELECT customer_name,
	   product_name,
	   Total_price,
	   gender,
	   delivery_status
FROM shop_data
WHERE gender = 'Female' AND total_price >3000 AND delivery_status = 'Delivered'
ORDER BY total_price DESC;



/*
Question 3 – Product Price Classification 🏷️ (CASE WHEN)

The pricing team wants every product to be classified.

Display:

Product_Name
Unit_Price
Price_Category

Rules:

Below 500 → Budget
500–2000 → Standard
Above 2000 → Premium
*/
SELECT product_name,
       Unit_price,
	   
	 CASE 
	 	WHEN total_price <500 then 'Budget'
		WHEN total_price BETWEEN 500 AND 2000 then 'Standard'
		else 'Premium'
	end AS price_category
	FROM shop_data;


