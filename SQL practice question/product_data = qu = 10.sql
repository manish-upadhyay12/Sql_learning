/*
=============================🔥 New Mixed Real-World Company Problem==============================

Imagine you're working as a Data Analyst at Amazon. The marketing manager asks:
"We are launching a campaign for premium Gmail customers who purchased electronics and received their orders successfully. Prepare a customer list."

Requirements:
Display:

Customer_Name, Product_Name in UPPERCASE, Brand with extra spaces removed, Email in lowercase
Phone number length
Total_Price

Conditions:

Only Electronics products
Delivery status = 'Delivered'
Email ends with gmail.com
Phone number must be exactly 10 characters
Total_Price greater than 1000

Finally, sort the results by Total_Price in descending order.

*/
SELECT   Customer_Name,
		UPPER(Product_Name) AS  UPPERCASE,
		TRIM(Brand) AS spaces_removed,
		LOWER(Email) AS EMAIL_lowercase,
		phone_number,
		Total_Price
FROM shop_data
WHERE product_category = 'Electronics'
	  AND Delivery_Status = 'Delivered'
	  AND email like  '%@gmail.com'
	  AND LENGTH(phone_number) = 10
	  AND total_price >1000;
	  

 
